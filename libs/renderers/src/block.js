// A managed block: the part of a hand-written file (AGENTS.md) that maggie owns.
// Everything outside the markers belongs to the repository and is never touched.

export function blockMarkers(id) {
  return {
    begin: `<!-- maggie:begin ${id} — generated by maggie, edit the skills library instead -->`,
    end: `<!-- maggie:end ${id} -->`,
  };
}

// The begin marker is matched on its prefix: the wording after the id may change between versions.
function locate(text, id) {
  const { end } = blockMarkers(id);
  const start = text.indexOf(`<!-- maggie:begin ${id} `);
  if (start === -1) return null;
  const beginClose = text.indexOf('-->', start);
  const close = beginClose === -1 ? -1 : text.indexOf(end, beginClose);
  if (close === -1) throw new Error(`unterminated maggie block "${id}": no "${end}"`);
  return { start, innerStart: beginClose + 3, innerStop: close, stop: close + end.length };
}

export function renderBlock(id, content) {
  const { begin, end } = blockMarkers(id);
  return `${begin}\n\n${content.trim()}\n\n${end}`;
}

/** `existing` with block `id` set to `content`: replaced in place, or appended. */
export function mergeBlock(existing, id, content) {
  const block = renderBlock(id, content);
  const text = existing ?? '';
  const found = locate(text, id);
  if (found) return `${text.slice(0, found.start)}${block}${text.slice(found.stop)}`;
  if (text.trim() === '') return `${block}\n`;
  return `${text.trimEnd()}\n\n${block}\n`;
}

/** `existing` without block `id`; an empty string when nothing else was in the file. */
export function removeBlock(existing, id) {
  const found = locate(existing, id);
  if (!found) return existing;
  const before = existing.slice(0, found.start).trimEnd();
  const after = existing.slice(found.stop).trim();
  const rest = [before, after].filter(Boolean).join('\n\n');
  return rest ? `${rest}\n` : '';
}

/** The content of block `id` in `existing`, or null when the file has none. */
export function readBlock(existing, id) {
  if (typeof existing !== 'string') return null;
  const found = locate(existing, id);
  return found ? existing.slice(found.innerStart, found.innerStop).trim() : null;
}
