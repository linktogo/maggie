import { test } from 'node:test';
import assert from 'node:assert/strict';
import agents from '../../src/renderers/agents.js';

const skill = {
  name: 'nestjs-module-structure',
  description: 'How to structure NestJS modules',
  globs: ['**/*.ts'],
  body: '# Module structure',
  source: 'skills/nestjs/module-structure/SKILL.md',
};

test('agents renders the Agent Skills layout: .agents/skills/<name>/SKILL.md', () => {
  const { path, content } = agents.render(skill);
  assert.equal(path, '.agents/skills/nestjs-module-structure/SKILL.md');
  assert.equal(
    content,
    '---\nname: "nestjs-module-structure"\ndescription: "How to structure NestJS modules"\n---\n\n<!-- Generated by maggie from skills/nestjs/module-structure/SKILL.md — edit there, not here. -->\n\n# Module structure\n',
  );
});

test('agents keeps supporting files next to SKILL.md', () => {
  assert.equal(agents.id, 'agents');
  assert.equal(agents.resourceRoot(skill), '.agents/skills/nestjs-module-structure');
});

test('agents indexes the skills in an AGENTS.md block, sorted, with table-safe descriptions', () => {
  const index = agents.renderIndex([
    { name: 'zeta', description: 'Last | one\nwrapped' },
    { name: 'alpha', description: 'First' },
  ]);
  assert.equal(index.path, 'AGENTS.md');
  assert.equal(index.block, 'skills');
  const lines = index.content.split('\n');
  assert.equal(lines[0], '## Agent skills');
  assert.deepEqual(lines.slice(-2), [
    '| [`alpha`](.agents/skills/alpha/SKILL.md) | First |',
    '| [`zeta`](.agents/skills/zeta/SKILL.md) | Last \\| one wrapped |',
  ]);
});
